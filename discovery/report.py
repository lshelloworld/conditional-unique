"""Turn results/{hockey,voc}.json into a ranked Markdown report for the experiments."""
import json, os, re, sys
from collections import Counter

ORDER = {'pos': 0, 'dom': 1, 'part': 2, 'cert': 3, 'cand': 4}
NAME = {'pos': 'possible', 'dom': 'domain', 'part': 'partial', 'cert': 'certain', 'cand': 'candidate'}

def short(t): return t.split('.')[-1]

def keyfmt(r): return f"{NAME[r['cls']]}({', '.join(r['K'])})"

def dedupe(rows):
    """one entry per (table, K, class, scope): conditions with the same scope are listed once"""
    seen, out = set(), []
    for r in rows:
        k = (r['table'], tuple(r['K']), r['cls'], r['support'], r['rows'])
        if k in seen: continue
        seen.add(k); out.append(r)
    return out

def section(lines, title, rows, cols):
    lines.append(f'\n### {title}\n')
    if not rows:
        lines.append('_None._\n'); return
    lines.append('| # | ' + ' | '.join(h for h, _ in cols) + ' |')
    lines.append('|' + '---|' * (len(cols) + 1))
    for i, r in enumerate(rows, 1):
        lines.append(f'| {i} | ' + ' | '.join(str(f(r)).replace('|', '\\|') for _, f in cols) + ' |')

def main(datasets):
    L = ['# Conditional keys discovered on Hockey, VOC, NCVoter and UniProt', '',
         'Generated by `discovery/run.py`, `discovery/run_csv.py` and `discovery/report.py`. The Hockey and '
         'VOC exports are pseudonymised, so their constants are shown by frequency rank within the column '
         '(`lgID = v1 (63%)` is the most frequent league; the JSON keeps the hashed value). NCVoter and '
         'UniProt are plaintext. NCVoter was mined on all 1,023,993 records with curated key columns (person '
         'attributes) and condition columns (status, reason, party, demographics, flags); keys mined on a '
         '100,000-row sample did not hold on the full data and are superseded. The UniProt file holds 24,173 '
         'complete records (it is truncated relative to its name), all of which were mined. Possible keys '
         'are ranked by the share of in-scope records that have all key values (SQL UNIQUE ignores the '
         'others), and keys on columns that are more than 80% empty are treated as accidental. Every listed exact key was re-checked on the data by an independent '
         'test (column *ok*).', '']
    for ds in datasets:
        path = f'results/{ds}.json'
        if not os.path.exists(path): continue
        D = json.load(open(path))
        allc = [r for t in D['tables'] for r in t['conditional']]
        alla = [r for t in D['tables'] for r in t['approximate']]
        L.append(f'\n## {ds.upper().replace("-FULL", "")}\n')
        L.append('| table | rows | unconditional keys | conditional keys | approximate |')
        L.append('|---|---|---|---|---|')
        for t in D['tables']:
            L.append(f"| {short(t['table'])} | {t['rows']} | {len(t['unconditional'])} | "
                     f"{t['n_conditional']} | {t['n_approximate']} |")
        nrate = {}
        for t in D['tables']: nrate.update(t.get('null_rate', {}))
        sparse = lambda r: any(nrate.get(c, 0) > 0.8 for c in r['K'])
        eff = lambda r: r['score'] * ((1 - r['nulls_in_scope']) if r['cls'] == 'pos' else 1)
        curated = bool(D['params'].get('key_cols')) and ds.endswith('-full')   # key columns chosen by hand
        good = [r for r in allc if ('accidental?' not in r['tags'] or curated) and r['verified'] is not False
                and not sparse(r) and not (r['cls'] == 'pos' and r['nulls_in_scope'] > 0.5)]
        good.sort(key=lambda r: -eff(r))
        good = dedupe(good)
        # spread over tables: at most 4 per table in the overall list
        per, top = Counter(), []
        for r in good:
            if per[r['table']] < 4: top.append(r); per[r['table']] += 1
            if len(top) == 25: break
        cols = [('table', lambda r: short(r['table'])), ('key', keyfmt), ('condition', lambda r: r['condition']),
                ('scope', lambda r: f"{r['rows']} ({r['support']:.0%})"),
                ('unconditionally', lambda r: NAME.get(r['uncond'], 'no key')),
                ('ok', lambda r: {True: 'yes', None: '-', False: 'NO'}[r['verified']])]
        section(L, 'Top conditional keys (identifier-like columns, ranked)', top, cols)
        qo = [r for r in good if 'QO' in r['tags'] and r['uncond'] is None][:15]
        section(L, 'For query optimisation: keys that hold only under a predicate', qo,
                [('table', lambda r: short(r['table'])), ('key', keyfmt),
                 ('WHERE predicate', lambda r: f"`{r['sql']}`"), ('scope', lambda r: f"{r['support']:.0%}"),
                 ('licensed rewrites', lambda r: {'pos': 'join elimination, IN/semi-join (NOT DISTINCT/GROUP BY)',
                                                  'dom': 'DISTINCT / GROUP BY removal, join elimination',
                                                  'part': 'drop subsumption removal',
                                                  'cert': 'one compatible match; certain-answer rewrites',
                                                  'cand': 'all of the above (total within scope)'}[r['cls']])])
        trap = [r for r in good if 'GROUP-BY-trap' in r['tags']][:10]
        section(L, 'GROUP BY traps: possible key holds, domain key fails in the scope', trap, cols[:5])
        ns = [r for r in good if 'null-semantics' in r['tags']][:12]
        section(L, 'Null semantics matter: partial/certain keys with missing key values in the scope', ns,
                cols[:3] + [('nulls in scope', lambda r: f"{r['nulls_in_scope']:.0%}")] + cols[3:5])
        ap = sorted([r for r in alla if not sparse(r)], key=lambda r: (r['violating_pairs'], -r['support'], len(r['K'])))
        seen, seen_rows, aps = set(), set(), []
        for r in ap:
            k = (r['table'], tuple(r['K']), r['cls'])
            rk = (r['table'], tuple(r['violating_rows']))
            if k in seen or rk in seen_rows or r['support'] < 0.2: continue
            seen.add(k); seen_rows.add(rk); aps.append(r)
            if len(aps) == 15: break
        section(L, 'For data cleaning: near-holding conditional keys (violating rows are candidate errors)', aps,
                [('table', lambda r: short(r['table'])), ('key', keyfmt), ('condition', lambda r: r['condition']),
                 ('scope', lambda r: f"{r['support']:.0%}"), ('violating pairs', lambda r: r['violating_pairs']),
                 ('rows (0-based)', lambda r: ', '.join(map(str, r['violating_rows'][:6])) + (' ...' if len(r['violating_rows']) > 6 else ''))])
    open('report.md', 'w').write('\n'.join(L) + '\n')
    print('wrote report.md')

if __name__ == '__main__':
    main(sys.argv[1:] or ['hockey', 'voc', 'ncvoter-full', 'uniprot'])
