IF DB_ID('p') IS NULL CREATE DATABASE p;
GO
USE p;
GO
DROP TABLE IF EXISTS a, bu, bf, bn, bfs;
CREATE TABLE a (id int PRIMARY KEY, bk int, v int);
CREATE TABLE bu (id int PRIMARY KEY, k int NOT NULL, d int, x int, CONSTRAINT bu_k UNIQUE (k));
CREATE TABLE bf (id int PRIMARY KEY, k int NOT NULL, d int, x int);
CREATE UNIQUE INDEX bf_k ON bf (k) WHERE d IS NULL;
CREATE TABLE bn (id int PRIMARY KEY, k int);
CREATE UNIQUE INDEX bn_k ON bn (k) WHERE k IS NOT NULL;
CREATE TABLE bfs (id int PRIMARY KEY, k int NOT NULL, st int, d int);
CREATE UNIQUE INDEX bfs_k ON bfs (k) WHERE st IN (0, 1);
GO
INSERT INTO a SELECT value, value % 100, value FROM GENERATE_SERIES(1, 1000);
INSERT INTO bu SELECT value, value, NULL, value % 7 FROM GENERATE_SERIES(1, 100);
INSERT INTO bf SELECT value, value % 100, CASE WHEN value <= 100 THEN NULL ELSE value END, value % 7 FROM GENERATE_SERIES(1, 300);
INSERT INTO bn SELECT value, CASE WHEN value % 3 = 0 THEN NULL ELSE value END FROM GENERATE_SERIES(1, 100);
INSERT INTO bfs SELECT value, value % 100, CASE WHEN value <= 100 THEN 0 ELSE 2 END, NULL FROM GENERATE_SERIES(1, 300);
GO
UPDATE STATISTICS a; UPDATE STATISTICS bu; UPDATE STATISTICS bf; UPDATE STATISTICS bn; UPDATE STATISTICS bfs;
GO
